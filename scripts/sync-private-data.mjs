#!/usr/bin/env node
/**
 * Content-addressed sync of data/private/*.json to Vercel Blob (private access).
 *
 * WHY THIS EXISTS
 * ---------------
 * Every deployment's serverless function bundle used to carry ~48MB of JSON out
 * of data/private/ (community-investment.json alone is 42MB), because the five
 * loaders read those files with `readFileSync(path.join(process.cwd(), …))` and
 * next.config.ts declared them in `outputFileTracingIncludes`. Multiplied by
 * every function and every retained deployment that pushed Vercel Functions
 * Storage for this project to 20GB.
 *
 * The files themselves are NOT the problem — they are committed, and
 * data/private/README.md's rule stands: they are served only through gated APIs
 * and must never move into public/. What was wrong was shipping them inside the
 * function bundle. So: next.config.ts now EXCLUDES data/private/** from tracing,
 * and lib/private-data.ts reads each file from disk when it is there (dev,
 * tests, CI) and from a PRIVATE Vercel Blob when it is not (production).
 *
 * CONTENT ADDRESSING
 * ------------------
 * pathname = private-data/<first 16 hex of sha256(contents)>/<filename>
 *
 * That makes the blob immutable per version of the data: a refreshed export gets
 * a new hash and therefore a new pathname, so a deploy can never read a stale
 * body under a name that was overwritten, and a rollback to an older deployment
 * still finds the exact bytes its manifest names. It also makes this script a
 * no-op on re-run — the blob for a hash either exists or it does not.
 *
 * data/private-manifest.json is a pure function of the file contents, so it is
 * deterministic and safe to commit. CI (which has no BLOB_READ_WRITE_TOKEN)
 * regenerates it and exits 0; the Vercel build, which HAS the token, uploads
 * anything the manifest names that is not in the store yet.
 */

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const PRIVATE_DIR = path.join(REPO_ROOT, "data", "private");
const MANIFEST_PATH = path.join(REPO_ROOT, "data", "private-manifest.json");

/** Files at or above this size go up as a multipart upload. */
const MULTIPART_THRESHOLD_BYTES = 10 * 1024 * 1024;

/** @typedef {{ pathname: string; sha256: string; bytes: number }} ManifestEntry */

async function buildManifest() {
  let names;
  try {
    names = await readdir(PRIVATE_DIR);
  } catch (err) {
    if (err && err.code === "ENOENT") return { entries: {}, bodies: new Map() };
    throw err;
  }

  const jsonNames = names.filter((n) => n.endsWith(".json")).sort();
  /** @type {Record<string, ManifestEntry>} */
  const entries = {};
  /** @type {Map<string, Buffer>} */
  const bodies = new Map();

  for (const filename of jsonNames) {
    const body = await readFile(path.join(PRIVATE_DIR, filename));
    const sha256 = createHash("sha256").update(body).digest("hex");
    entries[filename] = {
      pathname: `private-data/${sha256.slice(0, 16)}/${filename}`,
      sha256,
      bytes: body.byteLength,
    };
    bodies.set(filename, body);
  }

  return { entries, bodies };
}

/**
 * Write the manifest only when it actually changed, so a build on unchanged data
 * leaves the working tree clean (the data-refresh workflow diffs it).
 */
async function writeManifestIfChanged(entries) {
  const next = `${JSON.stringify(
    {
      $comment:
        "Generated by scripts/sync-private-data.mjs. Content-addressed pointers to the private JSON in Vercel Blob; a pure function of data/private/*.json contents. Do not hand-edit.",
      files: entries,
    },
    null,
    2,
  )}\n`;

  let current = null;
  try {
    current = await readFile(MANIFEST_PATH, "utf8");
  } catch {
    /* first run */
  }
  if (current === next) return false;
  await writeFile(MANIFEST_PATH, next, "utf8");
  return true;
}

async function main() {
  const { entries, bodies } = await buildManifest();
  const fileCount = Object.keys(entries).length;
  const changed = await writeManifestIfChanged(entries);

  console.log(
    `sync-private-data: manifest ${changed ? "updated" : "unchanged"} (${fileCount} file${
      fileCount === 1 ? "" : "s"
    }) -> data/private-manifest.json`,
  );

  if (!process.env.BLOB_READ_WRITE_TOKEN) {
    console.log(
      "sync-private-data: BLOB_READ_WRITE_TOKEN is not set — manifest regenerated, no upload attempted.",
    );
    return;
  }

  if (fileCount === 0) {
    console.log("sync-private-data: no data/private/*.json on disk — nothing to upload.");
    return;
  }

  const { BlobNotFoundError, head, put } = await import("@vercel/blob");

  let uploaded = 0;
  let skipped = 0;

  for (const [filename, entry] of Object.entries(entries)) {
    let exists = false;
    try {
      await head(entry.pathname);
      exists = true;
    } catch (err) {
      // BlobNotFoundError is the expected "not uploaded yet" answer. Anything
      // else (auth, network, a suspended store) is a real failure and must not
      // be swallowed into a silent re-upload attempt that also fails.
      //
      // Matched by `instanceof`, not by `err.name`: every error class in
      // @vercel/blob is an anonymous `class extends BlobError`, so they all
      // report `name === "Error"` and a name check would swallow an auth
      // failure as a cache miss.
      if (!(err instanceof BlobNotFoundError)) throw err;
    }

    if (exists) {
      skipped += 1;
      console.log(`  skip    ${filename} -> ${entry.pathname} (already in store)`);
      continue;
    }

    try {
      await put(entry.pathname, bodies.get(filename), {
        access: "private",
        addRandomSuffix: false,
        contentType: "application/json",
        multipart: entry.bytes >= MULTIPART_THRESHOLD_BYTES,
      });
    } catch (err) {
      // The one misconfiguration worth naming explicitly. `access: "private"`
      // is not optional here: data/private/README.md's rule is that these files
      // are served only through gated APIs, so a public store is not an
      // acceptable fallback — it would publish a named-entity dossier at a
      // guessable URL. Fail the build instead, loudly, with the fix.
      if (String(err?.message ?? "").includes("private access on a public store")) {
        throw new Error(
          "The Blob store this token points at is PUBLIC. data/private/*.json may only be " +
            "stored with access:\"private\" (see data/private/README.md). Create a private " +
            "store and point BLOB_READ_WRITE_TOKEN at it:\n" +
            "  vercel blob create-store <name> --access private --environment production\n" +
            `Original error: ${err.message}`,
        );
      }
      throw err;
    }
    uploaded += 1;
    console.log(
      `  upload  ${filename} -> ${entry.pathname} (${(entry.bytes / 1024 / 1024).toFixed(1)} MB)`,
    );
  }

  console.log(`sync-private-data: ${uploaded} uploaded, ${skipped} already present.`);
}

main().catch((err) => {
  console.error("sync-private-data failed:", err);
  process.exit(1);
});
